# --- Dispatch ------------------------------------------------------------
switch ($Mode) {
  'init'           { Invoke-Init }
  'validate'       { Invoke-Validate }
  'show'           { Invoke-Show }
  'export-render'  { Invoke-ExportRender }
  'export-vercel'  { Invoke-ExportVercel }
  default          { Invoke-Help }
}
