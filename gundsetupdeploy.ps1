  Write-Banner 'EZProject Env Helper - gundsetupdeploy.ps1'
  Write-Host 'Cac lenh:'
  Write-Host ''
  Write-Host '  .\gundsetupdeploy.ps1 -Mode init             ' -NoNewline -ForegroundColor Green
