  Write-Host 'Vao Vercel -> Project -> Settings -> Environment Variables' -ForegroundColor Yellow
  Write-Host 'Paste tung dong duoi day:' -ForegroundColor Yellow
  Write-Host ''
  foreach ($k in ($map.Keys | Sort-Object)) {
    $v = $map[$k]
    if ([string]::IsNullOrEmpty($v)) {
      Write-Host "  [SKIP] $k - empty, dien tren Vercel" -ForegroundColor DarkGray
