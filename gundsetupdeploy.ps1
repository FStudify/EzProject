  Write-Host '  .\gundsetupdeploy.ps1 -Mode validate         ' -NoNewline -ForegroundColor Green
  Write-Host 'Kiem tra .env co du keys chua'
  Write-Host '  .\gundsetupdeploy.ps1 -Mode show             ' -NoNewline -ForegroundColor Green
